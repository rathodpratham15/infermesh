// Package tritonrepo sanity-checks a Triton model repository prepared for the
// TensorRT-LLM backend, so mistakes are caught on a laptop instead of after a
// slow GPU deployment fails.
//
// It checks structure and obvious template mistakes only. It does not load the
// model, parse protobuf text fully, or validate engine contents: those need
// Triton and an NVIDIA GPU. Anything that depends on a particular TensorRT-LLM
// release (parameter names) is reported as a warning, never an error, because
// those names change between releases.
package tritonrepo

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

type Severity string

const (
	Error   Severity = "error"
	Warning Severity = "warning"
)

type Problem struct {
	Severity Severity
	Path     string
	Message  string
}

func (p Problem) String() string {
	if p.Path == "" {
		return fmt.Sprintf("%s: %s", p.Severity, p.Message)
	}
	return fmt.Sprintf("%s: %s: %s", p.Severity, p.Path, p.Message)
}

// HasErrors reports whether any problem is an error.
func HasErrors(ps []Problem) bool {
	return slices.ContainsFunc(ps, func(p Problem) bool { return p.Severity == Error })
}

var (
	placeholderRE = regexp.MustCompile(`\$\{[^}]*\}`)
	nameRE        = regexp.MustCompile(`(?m)^name:\s*"([^"]*)"`)
	backendRE     = regexp.MustCompile(`(?m)^backend:\s*"([^"]*)"`)
	enginePathRE  = regexp.MustCompile(`key:\s*"gpt_model_path"\s*value:\s*\{\s*string_value:\s*"([^"]*)"`)
)

// Check validates the model repository rooted at dir.
func Check(dir string) []Problem {
	var ps []Problem
	add := func(sev Severity, path, format string, a ...any) {
		ps = append(ps, Problem{sev, path, fmt.Sprintf(format, a...)})
	}

	if st, err := os.Stat(dir); err != nil || !st.IsDir() {
		add(Error, dir, "model repository directory does not exist")
		return ps
	}
	present := func(name string) bool {
		st, err := os.Stat(filepath.Join(dir, name))
		return err == nil && st.IsDir()
	}

	hasEnsemble, hasBLS := present("ensemble"), present("tensorrt_llm_bls")
	if !present("tensorrt_llm") {
		add(Error, dir, `missing model "tensorrt_llm"`)
	}
	if !hasEnsemble && !hasBLS {
		// triton-cli generates a repository whose client-facing model is named after the
		// model (for example "llama-3.1-8b-instruct"), so this is only a warning. The name
		// the gateway sends must match a model in this repository.
		add(Warning, dir, `no "ensemble" or "tensorrt_llm_bls" model; fine for layouts generated by triton-cli, but BACKEND_<NAME>_MODEL must then name the client-facing model in this repository`)
	}
	if hasEnsemble {
		for _, m := range []string{"preprocessing", "postprocessing"} {
			if !present(m) {
				add(Error, dir, `"ensemble" requires model %q, which is missing`, m)
			}
		}
	}

	for _, m := range []string{"ensemble", "tensorrt_llm_bls", "preprocessing", "tensorrt_llm", "postprocessing"} {
		if present(m) {
			ps = append(ps, checkModel(dir, m)...)
		}
	}
	return ps
}

func checkModel(root, model string) []Problem {
	var ps []Problem
	add := func(sev Severity, path, format string, a ...any) {
		ps = append(ps, Problem{sev, path, fmt.Sprintf(format, a...)})
	}
	mdir := filepath.Join(root, model)
	cfgPath := filepath.Join(mdir, "config.pbtxt")

	if !hasVersionDir(mdir) {
		add(Error, mdir, `no numeric version directory (expected e.g. "1/")`)
	}
	raw, err := os.ReadFile(cfgPath)
	if err != nil {
		add(Error, cfgPath, "config.pbtxt is missing")
		return ps
	}
	text := string(raw)

	// Unfilled template markers mean fill_template.py was skipped or incomplete.
	sc := bufio.NewScanner(strings.NewReader(text))
	for n := 1; sc.Scan(); n++ {
		for _, m := range placeholderRE.FindAllString(sc.Text(), -1) {
			add(Error, fmt.Sprintf("%s:%d", cfgPath, n), "unresolved template placeholder %s", m)
		}
	}

	if m := nameRE.FindStringSubmatch(text); m != nil && m[1] != model {
		add(Error, cfgPath, `config name %q does not match directory %q`, m[1], model)
	}

	if model == "tensorrt_llm" {
		if m := backendRE.FindStringSubmatch(text); m == nil || m[1] != "tensorrtllm" {
			got := "(none)"
			if m != nil {
				got = m[1]
			}
			add(Error, cfgPath, `backend must be "tensorrtllm", found %s`, got)
		}
		m := enginePathRE.FindStringSubmatch(text)
		switch {
		case m == nil:
			add(Warning, cfgPath, `no "gpt_model_path" parameter found; the engine location parameter name can differ between TensorRT-LLM releases, so check your release's template`)
		case m[1] == "":
			add(Error, cfgPath, `"gpt_model_path" is empty`)
		case !strings.HasPrefix(m[1], "/") && !placeholderRE.MatchString(m[1]):
			add(Warning, cfgPath, `engine path %q is not absolute; it is resolved inside the Triton container`, m[1])
		}
	}
	return ps
}

func hasVersionDir(mdir string) bool {
	entries, err := os.ReadDir(mdir)
	if err != nil {
		return false
	}
	for _, e := range entries {
		if e.IsDir() && regexp.MustCompile(`^\d+$`).MatchString(e.Name()) {
			return true
		}
	}
	return false
}
